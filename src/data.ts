export function getCorporatorById(id: string) {
  return CORPORATORS.find(c => c.id === id);
}

export function getMLAById(id: string) {
  return MLAS.find(m => m.id === id);
}

export function getComplaintsByCorporator(corpId: string) {
  return COMPLAINTS.filter(c => c.corporatorId === corpId);
}

export function getWardStats() {
  return CORPORATORS.map(corp => {
    const complaints = getComplaintsByCorporator(corp.id);
    const resolveRate = corp.totalComplaints > 0
      ? Math.round((corp.resolvedOnTime / corp.totalComplaints) * 100)
      : 0;
    return {
      ward: corp.ward,
      wardName: corp.wardName,
      corporator: corp,
      openComplaints: complaints.filter(c => c.status !== 'resolved').length,
      resolveRate,
    };
  });
}
